-- Supabase-native Aristocracy catalog, membership, purchase history, and atomic gold debit.

create table if not exists public.aristocracy_levels (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name_ar text not null,
  color_primary text not null default '#E9B949',
  color_secondary text not null default '#6B3D12',
  icon_url text,
  price_gold bigint not null check (price_gold > 0),
  duration_days smallint not null default 30 check (duration_days > 0),
  sort_order smallint not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.aristocracy_features (
  id bigint generated by default as identity primary key,
  level_id integer not null references public.aristocracy_levels(id) on delete cascade,
  feature_key text not null,
  name_ar text not null,
  description_ar text not null default '',
  icon text not null default '✦',
  sort_order smallint not null default 0,
  unique (level_id, feature_key)
);

create table if not exists public.aristocracy_purchases (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  level_id integer not null references public.aristocracy_levels(id),
  price_gold bigint not null check (price_gold > 0),
  duration_days smallint not null check (duration_days > 0),
  created_at timestamptz not null default now(),
  unique (user_id, request_id)
);

create index if not exists aristocracy_purchases_user_created_idx
  on public.aristocracy_purchases (user_id, created_at desc);

create table if not exists public.user_aristocracy (
  user_id uuid primary key references auth.users(id) on delete cascade,
  level_id integer not null references public.aristocracy_levels(id),
  started_at timestamptz not null,
  expires_at timestamptz not null,
  purchase_id uuid not null references public.aristocracy_purchases(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.saki_gold_ledger (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  amount bigint not null,
  balance_after bigint not null check (balance_after >= 0),
  reason text not null,
  reference_id uuid references public.aristocracy_purchases(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists saki_gold_ledger_user_created_idx
  on public.saki_gold_ledger (user_id, created_at desc);

alter table public.aristocracy_levels enable row level security;
alter table public.aristocracy_features enable row level security;
alter table public.aristocracy_purchases enable row level security;
alter table public.user_aristocracy enable row level security;
alter table public.saki_gold_ledger enable row level security;

drop policy if exists aristocracy_levels_select_active on public.aristocracy_levels;
create policy aristocracy_levels_select_active
  on public.aristocracy_levels for select to authenticated
  using (is_active = true);

drop policy if exists aristocracy_features_select_authenticated on public.aristocracy_features;
create policy aristocracy_features_select_authenticated
  on public.aristocracy_features for select to authenticated
  using (true);

drop policy if exists aristocracy_purchases_select_own on public.aristocracy_purchases;
create policy aristocracy_purchases_select_own
  on public.aristocracy_purchases for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists user_aristocracy_select_own on public.user_aristocracy;
create policy user_aristocracy_select_own
  on public.user_aristocracy for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists saki_gold_ledger_select_own on public.saki_gold_ledger;
create policy saki_gold_ledger_select_own
  on public.saki_gold_ledger for select to authenticated
  using (auth.uid() = user_id);

grant select on public.aristocracy_levels, public.aristocracy_features,
  public.aristocracy_purchases, public.user_aristocracy,
  public.saki_gold_ledger to authenticated;

