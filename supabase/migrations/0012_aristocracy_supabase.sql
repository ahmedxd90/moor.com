create or replace function public.purchase_aristocracy(
  p_level_id integer,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_level public.aristocracy_levels%rowtype;
  v_wallet public.room_wallets%rowtype;
  v_current public.user_aristocracy%rowtype;
  v_existing public.aristocracy_purchases%rowtype;
  v_purchase_id uuid;
  v_started_at timestamptz;
  v_expires_at timestamptz;
  v_balance bigint;
  v_now timestamptz := now();
  v_status jsonb;
begin
  if v_user_id is null then
    raise exception using message = 'not_authenticated';
  end if;
  if p_request_id is null then
    raise exception using message = 'invalid_purchase_request';
  end if;

  insert into public.room_wallets (user_id)
  values (v_user_id)
  on conflict (user_id) do nothing;

  select * into v_wallet
  from public.room_wallets
  where user_id = v_user_id
  for update;

  select * into v_existing
  from public.aristocracy_purchases
  where user_id = v_user_id and request_id = p_request_id;
  if found then
    select w.gold_coins into v_balance
    from public.room_wallets w where w.user_id = v_user_id;
    select jsonb_build_object(
      'level_id', ua.level_id,
      'started_at', ua.started_at,
      'expires_at', ua.expires_at,
      'level_name', l.name_ar,
      'slug', l.slug
    ) into v_status
    from public.user_aristocracy ua
    join public.aristocracy_levels l on l.id = ua.level_id
    where ua.user_id = v_user_id;
    return jsonb_build_object(
      'purchase_id', v_existing.id,
      'gold_coins', v_balance,
      'idempotent', true,
      'status', v_status
    );
  end if;

  select * into v_level
  from public.aristocracy_levels
  where id = p_level_id and is_active = true
  for share;
  if not found then
    raise exception using message = 'aristocracy_level_not_found';
  end if;

  select * into v_current
  from public.user_aristocracy
  where user_id = v_user_id
  for update;

  if found and v_current.expires_at > v_now and v_current.level_id >= p_level_id then
    raise exception using message = 'aristocracy_already_active_or_higher';
  end if;
  if v_wallet.gold_coins < v_level.price_gold then
    raise exception using message = 'insufficient_gold_coins';
  end if;

  v_started_at := v_now;
  if v_current.expires_at > v_now then
    v_started_at := v_current.expires_at;
  end if;
  v_expires_at := v_started_at + make_interval(days => v_level.duration_days::integer);
  v_purchase_id := gen_random_uuid();

  update public.room_wallets
  set gold_coins = gold_coins - v_level.price_gold,
      lifetime_spent_gold = lifetime_spent_gold + v_level.price_gold,
      wealth_level = public.calculate_wealth_level(lifetime_spent_gold + v_level.price_gold),
      updated_at = v_now
  where user_id = v_user_id
  returning gold_coins into v_balance;

  insert into public.aristocracy_purchases
    (id, request_id, user_id, level_id, price_gold, duration_days, created_at)
  values
    (v_purchase_id, p_request_id, v_user_id, v_level.id, v_level.price_gold, v_level.duration_days, v_now);

  insert into public.user_aristocracy
    (user_id, level_id, started_at, expires_at, purchase_id, updated_at)
  values
    (v_user_id, v_level.id, v_started_at, v_expires_at, v_purchase_id, v_now)
  on conflict (user_id) do update set
    level_id = excluded.level_id,
    started_at = excluded.started_at,
    expires_at = excluded.expires_at,
    purchase_id = excluded.purchase_id,
    updated_at = excluded.updated_at;

  insert into public.saki_gold_ledger
    (user_id, amount, balance_after, reason, reference_id, created_at)
  values
    (v_user_id, -v_level.price_gold, v_balance, 'aristocracy_purchase', v_purchase_id, v_now);

  v_status := jsonb_build_object(
    'level_id', v_level.id,
    'started_at', v_started_at,
    'expires_at', v_expires_at,
    'level_name', v_level.name_ar,
    'slug', v_level.slug
  );
  return jsonb_build_object(
    'purchase_id', v_purchase_id,
    'gold_coins', v_balance,
    'idempotent', false,
    'status', v_status
  );
end;
$$;

revoke all on function public.purchase_aristocracy(integer, uuid) from public;
revoke all on function public.purchase_aristocracy(integer, uuid) from anon;
grant execute on function public.purchase_aristocracy(integer, uuid) to authenticated;
